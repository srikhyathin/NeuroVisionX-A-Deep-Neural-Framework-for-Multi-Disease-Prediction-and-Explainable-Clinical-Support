from reportlab.lib import colors
from reportlab.lib.styles import getSampleStyleSheet
from reportlab.platypus import (
    SimpleDocTemplate,
    Paragraph,
    Spacer,
    Table,
    TableStyle
)

from reportlab.lib.units import inch
from datetime import datetime
import os


class ReportGenerator:

    def __init__(self):

        self.styles = getSampleStyleSheet()

        os.makedirs("reports", exist_ok=True)

    def generate_report(
        self,
        patient_name,
        age,
        gender,
        prediction,
        confidence,
        symptoms,
        description,
        precautions,
        model_used
    ):
        
        filename = f"reports/{patient_name.replace(' ','_')}_{datetime.now().strftime('%Y%m%d_%H%M%S')}.pdf"

        doc = SimpleDocTemplate(filename)

        elements = []

        title = Paragraph(
            "<b><font size=20>NeuroVisionX Medical Report</font></b>",
            self.styles["Title"]
        )

        elements.append(title)
        elements.append(Spacer(1,0.3*inch))

        elements.append(
            Paragraph(
                f"<b>Date:</b> {datetime.now()}",
                self.styles["BodyText"]
            )
        )

        elements.append(Spacer(1,0.2*inch))

        data = [

            ["Patient Name", patient_name],

            ["Age", age],

            ["Gender", gender],

            ["Prediction", prediction],

            ["Confidence", f"{confidence:.2f}%"],

            ["AI Model", model_used]

        ]

        table = Table(data,colWidths=[2.2*inch,4*inch])

        table.setStyle(

            TableStyle([

                ('BACKGROUND',(0,0),(-1,0),colors.darkblue),

                ('TEXTCOLOR',(0,0),(-1,0),colors.white),

                ('GRID',(0,0),(-1,-1),1,colors.black),

                ('BACKGROUND',(0,1),(0,-1),colors.lightgrey),

                ('BOTTOMPADDING',(0,0),(-1,0),10)

            ])

        )

        elements.append(table)

        elements.append(Spacer(1,0.3*inch))

        elements.append(

            Paragraph(

                "<b>Symptoms</b>",

                self.styles["Heading2"]

            )

        )

        elements.append(

            Paragraph(

                ", ".join(symptoms),

                self.styles["BodyText"]

            )

        )

        elements.append(Spacer(1,0.2*inch))

        elements.append(

            Paragraph(

                "<b>Disease Description</b>",

                self.styles["Heading2"]

            )

        )

        elements.append(

            Paragraph(

                description,

                self.styles["BodyText"]

            )

        )

        elements.append(Spacer(1,0.2*inch))

        elements.append(

            Paragraph(

                "<b>Precautions</b>",

                self.styles["Heading2"]

            )

        )

        for item in precautions:

            elements.append(

                Paragraph(

                    f"• {item}",

                    self.styles["BodyText"]

                )

            )

        elements.append(Spacer(1,0.3*inch))

        elements.append(

            Paragraph(

                "<b>Disclaimer</b>",

                self.styles["Heading2"]

            )

        )

        elements.append(

            Paragraph(

                "This report is generated by NeuroVisionX AI. It is intended for educational and decision-support purposes only and should not replace professional medical advice or diagnosis.",

                self.styles["BodyText"]

            )

        )

        doc.build(elements)

        return filename